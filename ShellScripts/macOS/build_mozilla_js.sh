#!/bin/bash
# Builds the Mozilla JS (SpiderMonkey 1.8.5 / Firefox 4) static library for macOS.
#
# The upstream configure script requires Python 2 and does not know about Apple Silicon,
# so the sources are compiled directly. Only the interpreter is built: the tracing JIT,
# method JIT and YARR regexp JIT do not support arm64.
#
# Output (where src/meson/darwin/meson.build looks for it):
#   build/mozilla_js/lib/libjs_static.a      (release)
#   build/mozilla_js/lib/libjsdbg_static.a   (debug)
#   build/mozilla_js/include/*.h
#
# Requires: Xcode command line tools, git and Homebrew nspr.

set -euo pipefail

SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" &> /dev/null && pwd)
PROJECT_ROOT=$(cd "$SCRIPT_DIR/../.." && pwd)

MOZJS_REPO="https://github.com/OoliteProject/mozillajs-linux.git"
MOZJS_COMMIT="bc12f7124166c199925f3cea37d2732d3704213d"

WORK_DIR="$PROJECT_ROOT/build/mozjs-src"
OUT_DIR="$PROJECT_ROOT/build/mozilla_js"
JOBS=$(sysctl -n hw.ncpu)

NSPR_PREFIX=$(brew --prefix nspr 2> /dev/null || true)
if [[ -z "$NSPR_PREFIX" || ! -d "$NSPR_PREFIX/include/nspr" ]]; then
    echo "❌ nspr not found. Run: brew install nspr" >&2
    exit 1
fi

if [[ ! -d "$WORK_DIR/.git" ]]; then
    git clone "$MOZJS_REPO" "$WORK_DIR"
fi
git -C "$WORK_DIR" fetch --depth 1 origin "$MOZJS_COMMIT" 2> /dev/null || true
git -C "$WORK_DIR" checkout -q "$MOZJS_COMMIT"
git -C "$WORK_DIR" checkout -q -- .  # discard previously applied patches
git -C "$WORK_DIR" apply "$SCRIPT_DIR/mozilla_js_arm64.patch"

SRC="$WORK_DIR/js/src"

CORE_SOURCES=(
    jsanalyze.cpp jsapi.cpp jsarena.cpp jsarray.cpp jsatom.cpp jsbool.cpp jsclone.cpp
    jscntxt.cpp jscompartment.cpp jsdate.cpp jsdbgapi.cpp jsdhash.cpp jsdtoa.cpp jsemit.cpp
    jsexn.cpp jsfriendapi.cpp jsfun.cpp jsgc.cpp jsgcchunk.cpp jsgcstats.cpp jshash.cpp
    jsinterp.cpp jsinvoke.cpp jsiter.cpp jslock.cpp jslog2.cpp jsmath.cpp jsnativestack.cpp
    jsnum.cpp jsobj.cpp json.cpp jsopcode.cpp jsparse.cpp jsproxy.cpp jsprf.cpp jsprobes.cpp
    jspropertycache.cpp jspropertytree.cpp jsreflect.cpp jsregexp.cpp jsscan.cpp jsscope.cpp
    jsscript.cpp jsstr.cpp jstypedarray.cpp jsutil.cpp jswrapper.cpp jsxdrapi.cpp jsxml.cpp
    prmjtime.cpp sharkctl.cpp perf/jsperf.cpp perf/pm_stub.cpp
    v8-dtoa/checks.cc v8-dtoa/conversions.cc v8-dtoa/diy-fp.cc v8-dtoa/v8-dtoa.cc
    v8-dtoa/fast-dtoa.cc v8-dtoa/platform.cc v8-dtoa/utils.cc
    yarr/pcre/pcre_compile.cpp yarr/pcre/pcre_exec.cpp yarr/pcre/pcre_tables.cpp
    yarr/pcre/pcre_xclass.cpp yarr/pcre/pcre_ucp_searchfuncs.cpp
)

write_config_headers() {  # $1 = generated header directory
    cat > "$1/js-config.h" << 'EOF'
#ifndef js_config_h___
#define js_config_h___

/* Generated by ShellScripts/macOS/build_mozilla_js.sh (interpreter-only build). */

#define JS_THREADSAFE 1
#define JS_HAVE_STDINT_H 1
#define JS_BYTES_PER_WORD 8

#endif /* js_config_h___ */
EOF

    cat > "$1/js-confdefs.h" << 'EOF'
#ifndef _JS_CONFDEFS_H_
#define _JS_CONFDEFS_H_

#define XP_UNIX 1
#define XP_MACOSX 1
#define DARWIN 1
#define JS_HAVE_STDINT_H 1
#define JS_BYTES_PER_WORD 8
#define JS_BITS_PER_WORD_LOG2 6
#define JS_ALIGN_OF_POINTER 8
#define JS_THREADSAFE 1
#define NSPR_LOCK 1
#define HAVE_VA_COPY 1
#define VA_COPY va_copy
#define HAVE_LOCALTIME_R 1
#define HAVE_GETC_UNLOCKED 1
#define HAVE_TM_ZONE_TM_GMTOFF 1
#define HAVE_LOCALECONV 1
#define HAVE_VISIBILITY_ATTRIBUTE 1
#define HAVE_SYS_MMAN_H 1
#define MOZ_TRACE_JSCALLS 1
#define EXPORT_JS_API 1
#define __STDC_LIMIT_MACROS 1

#endif /* _JS_CONFDEFS_H_ */
EOF

    cat > "$1/jsautocfg.h" << 'EOF'
#ifndef js_cpucfg___
#define js_cpucfg___

/* Generated by ShellScripts/macOS/build_mozilla_js.sh. */

#define IS_LITTLE_ENDIAN 1
#undef IS_BIG_ENDIAN
#define JS_STACK_GROWTH_DIRECTION (-1)

#endif /* js_cpucfg___ */
EOF
}

build_variant() {  # $1 = release|debug
    local variant="$1"
    local obj_dir="$WORK_DIR/build-macos-$variant"
    local gen_dir="$obj_dir/gen"
    rm -rf "$obj_dir"
    mkdir -p "$gen_dir"

    write_config_headers "$gen_dir"

    local common_flags=(
        -arch arm64
        -mmacosx-version-min=11.0
        -fno-strict-aliasing
        -fno-exceptions
        -fPIC
        -include "$gen_dir/js-confdefs.h"
        -I"$gen_dir" -I"$SRC" -I"$SRC/assembler" -I"$SRC/yarr" -I"$SRC/perf"
        -I"$NSPR_PREFIX/include/nspr"
        -w
    )
    if [[ "$variant" == "debug" ]]; then
        common_flags+=(-O0 -g -DDEBUG -D_DEBUG -DJS_GC_ZEAL=1)
    else
        common_flags+=(-O2 -DNDEBUG -DJS_NO_JSVAL_JSID_STRUCT_TYPES=1)
    fi
    local cxx_flags=(-std=gnu++98 -fno-rtti "${common_flags[@]}")

    echo "--> Generating keyword and opcode tables ($variant)"
    clang++ "${cxx_flags[@]}" -o "$gen_dir/jskwgen" "$SRC/jskwgen.cpp"
    "$gen_dir/jskwgen" "$gen_dir/jsautokw.h"
    clang++ "${cxx_flags[@]}" -o "$gen_dir/jsoplengen" "$SRC/jsoplengen.cpp"
    "$gen_dir/jsoplengen" "$gen_dir/jsautooplen.h"

    echo "--> Compiling SpiderMonkey ($variant) with $JOBS jobs"
    local objects=()
    for src in "${CORE_SOURCES[@]}"; do
        objects+=("$obj_dir/$(echo "$src" | tr '/' '_').o")
    done
    # Flags go in a response file because BSD xargs limits the command length.
    printf '%s\n' "${cxx_flags[@]}" > "$obj_dir/flags.rsp"
    printf '%s\n' "${CORE_SOURCES[@]}" | xargs -P "$JOBS" -n 1 bash -c '
        clang++ @"$0/flags.rsp" -c "$1/$2" -o "$0/$(echo "$2" | tr "/" "_").o" || { echo "❌ Failed: $2" >&2; exit 255; }
    ' "$obj_dir" "$SRC"

    local lib_name="libjs_static.a"
    [[ "$variant" == "debug" ]] && lib_name="libjsdbg_static.a"
    mkdir -p "$OUT_DIR/lib"
    rm -f "$OUT_DIR/lib/$lib_name"
    ar rcs "$OUT_DIR/lib/$lib_name" "${objects[@]}"
    echo "✅ Built $OUT_DIR/lib/$lib_name"
}

install_headers() {
    local gen_dir="$WORK_DIR/build-macos-release/gen"
    rm -rf "$OUT_DIR/include"
    mkdir -p "$OUT_DIR/include"
    cp "$SRC"/*.h "$SRC"/*.tbl "$OUT_DIR/include/"
    cp "$gen_dir/js-config.h" "$gen_dir/jsautocfg.h" "$gen_dir/jsautokw.h" "$gen_dir/jsautooplen.h" "$OUT_DIR/include/"
}

if (($# == 0)); then
    set -- release debug  # build both variants by default
fi
for v in "$@"; do
    build_variant "$v"
done
install_headers
echo "✅ Mozilla JS installed to $OUT_DIR"
