// NSStringEncoding's values for the five code pages OOEncodingConverter names.
enum class Encoding : unsigned {
    windowsCP1251 = 11, // "windows-cyrillic"
    windowsCP1252 = 12, // "windows-latin-1"
    windowsCP1253 = 13, // "windows-greek"
    windowsCP1254 = 14, // "windows-turkish"
    windowsCP1250 = 15, // "windows-latin-2"
};

// StringFromEncoding().
constexpr const char* encodingName(Encoding e) noexcept
{
    switch (e) {
    case Encoding::windowsCP1252:
        return "windows-latin-1";
    case Encoding::windowsCP1250:
        return "windows-latin-2";
    case Encoding::windowsCP1251:
        return "windows-cyrillic";
    case Encoding::windowsCP1253:
        return "windows-greek";
    case Encoding::windowsCP1254:
        return "windows-turkish";
    }
    return nullptr;
}

// EncodingFromString(): exact, case-sensitive names; anything else is NSNotFound (nullopt).
constexpr std::optional<Encoding> encodingFromName(std::string_view name) noexcept
{
    if (name == "windows-latin-1")
        return Encoding::windowsCP1252;
    if (name == "windows-latin-2")
        return Encoding::windowsCP1250;
    if (name == "windows-cyrillic")
        return Encoding::windowsCP1251;
    if (name == "windows-greek")
        return Encoding::windowsCP1253;
    if (name == "windows-turkish")
        return Encoding::windowsCP1254;
    return std::nullopt;
}

