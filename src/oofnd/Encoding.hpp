/*	oofnd/Encoding.hpp
        oo::str encodings: the text-encoding half of OOEncodingConverter (bead oo-dps, proposed
        ADR-0034). The HUD font draws glyphs indexed by the bytes of a Windows code page; every string
        it draws is converted with GNUstep's lossy conversion first.

            Foundation / OOEncodingConverter              oo::str
            --------------------------------------------  ----------------------------------------------
            NSWindowsCP1250...1254StringEncoding          oo::str::Encoding  (same numeric values)
            EncodingFromString(name)                      oo::str::encodingFromName(name)  (nullopt: NSNotFound)
            StringFromEncoding(e)                         oo::str::encodingName(e)
            [s dataUsingEncoding:e                        oo::str::encodeLossy(s, e)  (nullopt: nil)
                allowLossyConversion:YES]
            -[OOEncodingConverter                         oo::str::convertForFont(s, e, substitutions)
                performConversionForString:]              (the OOCache in front of it stays game-side)

        GNUstep 1.31 converts through libiconv with transliteration, so an unencodable character is not
        simply '?'. Captured over every code point in all five code pages and a string corpus
        (tests/unit/oofnd/test_encoding.cpp), the conversion is, per code point:

          * its byte in the code page, if it has one (0x00..0x7F are ASCII in all five);
          * else the first of its transliterations (the tables below, e.g. U+0106 -> "<acute>C" or "'C",
            U+1F600 -> ":-D") whose every character has a byte in the code page;
          * else '?' for each UTF-16 unit (so "??" for an unmapped supplementary character, '?' for a
            lone surrogate);
          * and the whole conversion fails (nil) when the string ends in a high surrogate.

        Header-only, C++20, compiles with -fno-exceptions.
*/

